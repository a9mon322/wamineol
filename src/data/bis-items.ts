export function getBisItemColor(item: { itemId?: number }): string {
  if (item.itemId && ITEM_RARITY[item.itemId]) {
    return RARITY_COLORS[ITEM_RARITY[item.itemId]];
  }
  return RARITY_COLORS.epic;
}

